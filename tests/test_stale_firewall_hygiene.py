"""Contract tests for scripts/stale_firewall_hygiene.ps1."""

from __future__ import annotations

import subprocess
import unittest
from pathlib import Path

from script_validation_support import ScriptValidationMixin

SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "stale_firewall_hygiene.ps1"


class StaleFirewallHygieneTests(ScriptValidationMixin, unittest.TestCase):
    def setUp(self) -> None:
        self.text = SCRIPT.read_text(encoding="utf-8")

    def test_preview_is_default_and_apply_is_opt_in(self) -> None:
        self.assertIn("[switch]$Apply", self.text)
        self.assertIn("if [ \"$APPLY\" != '1' ]; then", self.text)
        self.assertIn("STALE_FIREWALL_CONFIRM_APPLY_REQUIRED", self.text)
        self.assertIn("flock -n 9", self.text)
        self.assertIn("ROLLBACK_VERIFIED", self.text)

    def test_only_named_inactive_argo_rows_are_removed(self) -> None:
        text = self.text
        self.assertIn("systemctl is-active --quiet argo", text)
        self.assertIn("if [ \"$PROFILE\" = 'bwg' ]; then", text)
        self.assertIn('Replace("__PROFILE__", $Profile)', text)
        self.assertIn("STALE_FIREWALL_SERVICE_ACTIVE", text)
        self.assertIn("STALE_FIREWALL_PORT_IN_USE", text)
        self.assertIn('--comment "ArgoX PORT ', text)
        self.assertIn("STALE_FIREWALL_RULE_PARSE_FAILED", text)
        self.assertIn('python3 -c "', text)
        self.assertIn(
            'iptables -D INPUT -p "$proto" --dport "$port" '
            '-m comment --comment "$comment" -j ACCEPT',
            text,
        )

    def test_persists_after_a_live_change_and_verifies_both_layers(self) -> None:
        text = self.text
        self.assertIn("netfilter-persistent save", text)
        self.assertIn("STALE_FIREWALL_PERSISTENCE_UNSUPPORTED", text)
        self.assertIn("grep -q '^# Generated by iptables-save'", text)
        self.assertIn("STALE_FIREWALL_DELETE_INCOMPLETE", text)
        self.assertIn("iptables-restore --noflush", text)
        self.assertIn("stale_firewall_rules=", text)

    def test_embedded_payload_is_bash_syntax(self) -> None:
        payload = self.text.split("$remoteCommand = @'\n", 1)[1].split("\n'@", 1)[0]
        payload = payload.replace("\r\n", "\n").replace("\r", "\n")
        bash = self._resolve_bash()
        if bash is None:
            self.skipTest("Bash is not available")
        result = subprocess.run(
            self._bash_command(bash, "-n"),
            input=payload,
            text=True,
            capture_output=True,
            timeout=30,
            check=False,
        )
        self.assertEqual(result.returncode, 0, result.stderr)


if __name__ == "__main__":
    unittest.main()
